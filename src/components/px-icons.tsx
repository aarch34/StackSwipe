export type IconProps = SVGProps<SVGSVGElement> & {
  size?: number | string;
  strokeWidth?: number | string;
  absoluteStrokeWidth?: boolean;
};

// Same names and props as the Lucide icons they replace, so call sites stay untouched.
function px(Icon: ComponentType<SVGProps<SVGSVGElement>>, name: string) {
  function PixelIcon({ size = 24, strokeWidth, absoluteStrokeWidth, className, ...rest }: IconProps) {
    return (
      <Icon
        width={size}
        height={size}
        aria-hidden={rest['aria-label'] ? undefined : true}
        className={className ? `px-icon ${className}` : 'px-icon'}
        {...rest}
      />
    );
  }
  PixelIcon.displayName = name;
  return PixelIcon;
}

